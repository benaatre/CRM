import "server-only";

import { prisma } from "@/lib/prisma";

/**
 * حذف كل توكنات أجهزة مستخدم — يُستدعى من كل مسارات الخروج.
 *
 * لماذا «كل التوكنات» لا توكن الجهاز الحالي فقط: الخادم لا يعرف أي توكن يخصّ
 * الجهاز الذي ضغط «خروج» (التوكن يعيش في العميل ولا يُرسل مع طلب الخروج).
 * وترك توكن حيّ لجهاز خرج منه صاحبه = تسريب: عناوين إشعارات (أسماء عملاء)
 * تظهر على شاشة قفل جهاز لم يعد مسجّلًا. فنمسح الكل، والأجهزة التي ما زالت
 * مسجّلة تعيد التسجيل تلقائيًا عند فتح التطبيق (المكوّن يسجّل عند كل تركيب).
 *
 * best-effort: فشله لا يُفشِل الخروج نفسه — الخروج أهم من التنظيف.
 */
export async function dropUserTokens(userId: string): Promise<void> {
  try {
    await prisma.deviceToken.deleteMany({ where: { userId } });
  } catch (e) {
    console.error("[push] فشل حذف توكنات الأجهزة عند الخروج", e);
  }
}
